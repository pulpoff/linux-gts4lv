#!/usr/bin/env python3
"""Write a dtsi that lets ABL apply Samsung's downstream recovery_dtbo to the
mainline DTB: every label the overlays' __fixups__ reference is exported in
__symbols__ as an empty node under /masked-devices, which nothing probes.
Same approach as sdm670-google-common-dtbo-mask.dtsi (Pixel 3a).

usage: gen-dtbo-mask.py <recovery.img with the recovery_dtbo> <out.dtsi>"""
import re, struct, subprocess, sys

img = open(sys.argv[1], "rb").read()
size, off = struct.unpack_from("<IQ", img, 1632)
table = img[off:off + size]
count = struct.unpack_from(">I", table, 16)[0]

names = set()
for i in range(count):
    e = struct.unpack_from(">8I", table, 32 + 32 * i)
    src = subprocess.run(["dtc", "-q", "-I", "dtb", "-O", "dts", "-"],
                         input=table[e[1]:e[1] + e[0]], capture_output=True, check=True).stdout.decode()
    fixups = src[src.index("__fixups__ {"):]
    fixups = fixups[:fixups.index("};")]
    names |= set(re.findall(r"^\t\t([A-Za-z0-9_]+) = ", fixups, re.M))
names = sorted(names)

out = ["// SPDX-License-Identifier: GPL-2.0-only",
       "/*",
       " * Generated by gen-dtbo-mask.py from the recovery_dtbo of LineageOS 22.2's",
       " * recovery image. ABL refuses to boot unless that overlay applies, so its",
       " * labels are exported here and point at empty nodes nothing probes.",
       " */",
       "",
       "/ {",
       "\t__symbols__ {"]
out += ['\t\t%s = "/masked-devices/%s";' % (n, n) for n in names]
out += ["\t};", "", "\tmasked-devices {"]
# Referencing every node forces dtc to give it a phandle for the fixups.
out.append("\t\tmasked = " + ",\n\t\t\t ".join("<&_masked_%s>" % n for n in names) + ";")
out.append("")
out += ["\t\t_masked_%s: %s {};" % (n, n) for n in names]
out += ["\t};", "};", ""]
if "reserved_memory" in names:
    out += ["/* The overlay adds a second ramoops at our ramoops' address; keep it off. */",
            "&_masked_reserved_memory {",
            "\tramoops@A1300000 {",
            '\t\tstatus = "disabled";',
            "\t};",
            "};", ""]
open(sys.argv[2], "w").write("\n".join(out))
print(len(names), "labels ->", sys.argv[2])
